import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(import.meta.dir, "../../contracts/out");
const DEST = join(import.meta.dir, "../src/abi");
const CONTRACTS = {
	AeonAgentNFT: "aeonAgentNftAbi",
	AeonRegistry: "aeonRegistryAbi",
	AeonEscrow: "aeonEscrowAbi",
} as const;

mkdirSync(DEST, { recursive: true });
const files: string[] = [];
for (const [contract, name] of Object.entries(CONTRACTS)) {
	const artifact = JSON.parse(
		readFileSync(join(OUT, `${contract}.sol`, `${contract}.json`), "utf8"),
	) as { abi: unknown[] };
	const file = join(DEST, `${name}.ts`);
	writeFileSync(
		file,
		`// Generated by scripts/gen-abis.ts from packages/contracts. Do not edit.\nexport const ${name} = ${JSON.stringify(artifact.abi)} as const;\n`,
	);
	files.push(file);
	console.log(
		`${contract} -> src/abi/${name}.ts (${artifact.abi.length} entries)`,
	);
}

const fmt = Bun.spawnSync(["bunx", "biome", "format", "--write", ...files]);
if (fmt.exitCode !== 0) {
	console.error(fmt.stderr.toString());
	process.exit(1);
}
